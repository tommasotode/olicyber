iv = bytearray(16)
for i in range(16):
    iv[i] = sassy[i] ^ bigstring_len

try:
    with open("flag.enc", "rb") as f:
        ciphertext = f.read()

    cipher = AES.new(aes_key, AES.MODE_CBC, bytes(iv))
    plaintext = cipher.decrypt(ciphertext)

    print(plaintext)

except Exception as e:
    print(e)