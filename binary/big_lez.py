joint_step = 0x55aa55aa
for k in range(100):
    if k < len(intro):
        b = intro[k]
        term1 = (joint_step << 5) & 0xFFFFFFFF
        term2 = (joint_step >> 3) & 0xFFFFFFFF
        joint_step = (b ^ term1 ^ term2) & 0xFFFFFFFF

b_joint_step = joint_step.to_bytes(4, byteorder='little')

buf = b"hehechasinglighteverywherefindwithin"
xored_buf = bytearray(buf)
for j in range(len(xored_buf)):
    key_byte = b_joint_step[j % 4]
    xored_buf[j] ^= key_byte

aes_key = hashlib.sha256(xored_buf).digest()

s3 = " everywhere but within."
s2 = " Lookin' everywhere to find it,"
s1 = "hehe, aren't we all chasing the light mate?"
bigstring = s3 + s2 + s1
bigstring_len = len(bigstring)

